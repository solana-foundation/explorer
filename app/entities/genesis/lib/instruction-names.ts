// The program logs events by calling itself with this byte, as the Genesis SDK's `emitEventInstructionDiscriminator`
// does. Shank numbers EmitEvent by its position in the IDL instead, which no transaction carries.
const EMIT_EVENT_DISCRIMINATOR = 255;

/** The IDL name for a Genesis instruction discriminator, or `undefined` for a byte the vendored IDL does not know. */
export function getGenesisInstructionName(discriminator: number): string | undefined {
    return discriminator === EMIT_EVENT_DISCRIMINATOR ? 'EmitEvent' : NAMES_BY_DISCRIMINATOR[discriminator];
}

/**
 * The IDL name of a Genesis instruction from its program id and leading byte, or `undefined` when it is not
 * a Genesis instruction or the byte is unknown, so it composes with the other `NAME_SOURCES` resolvers.
 */
export function resolveGenesisInstructionName(programId: string, data: Uint8Array): string | undefined {
    if (programId !== GENESIS_PROGRAM_ADDRESS || data.length === 0) return undefined;
    return getGenesisInstructionName(data[0]);
}
